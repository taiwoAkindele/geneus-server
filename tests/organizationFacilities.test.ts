import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes, randomUUID } from 'node:crypto';
import { Patient, type Staff } from '#shared';
import { addStaff, asDevice, envelopeFor, registerScratchFacility, scratchDatabase, scratchFacilityCode, testApp } from './postgres.ts';
import { findRecord, insertRecord } from '../src/db/records.ts';
import { findStaffEmail } from '../src/email/verifications.ts';
import { verifyCredential } from '../src/devices/credentials.ts';

const proof = () => ({ deviceId: randomUUID(), deviceSecret: randomBytes(32).toString('base64url') });

test('organization facility creation reuses verified identity, isolates records and recovers a lost response without duplication', async (t) => {
  const db = await scratchDatabase(); t.after(() => db.drop());
  const app = testApp(db.sql); t.after(() => app.close());
  const a = await registerScratchFacility(db.sql);
  const nurse = await addStaff(db.sql, a, { role: 'nurse' });
  const post = (path: string, values: Record<string, unknown> = {}, staffId = a.admin.id) => app.inject({ method: 'POST', url: path, headers: asDevice(a.device.credential), payload: { actorStaffId: staffId, ...values } });
  const patientId = `${a.facility.id}-000001-K2`;
  await insertRecord(db.sql, 'patient', Patient.parse({ ...envelopeFor(a), id: patientId, patientId, type: 'patient', fullName: 'Synthetic primary facility patient', address: 'Synthetic address', sex: 'female', ageYears: 30 }));
  const defaults = await post('/organization/facilities/defaults');
  assert.equal(defaults.statusCode, 200, defaults.body);
  assert.equal(defaults.json().organization, null);
  assert.ok(defaults.json().administrator.verifiedEmail);
  assert.notEqual(defaults.json().administrator.verifiedEmail, await findStaffEmail(db.sql, a.facility.id, a.admin.id));
  const input = { code: scratchFacilityCode(), name: 'Synthetic second facility', state: 'Lagos', lga: 'Eti-Osa', level: 'general_hospital', organizationName: 'Synthetic healthcare group', requestId: randomUUID(), ...proof() };
  const created = await post('/organization/facilities', { ...input, adminEmail: 'not-the-admin@example.org', adminFullName: 'Ignored caller name' });
  assert.equal(created.statusCode, 201, created.body);
  const result = created.json();
  assert.equal(result.facility.name, input.name);
  assert.equal(result.admin.fullName, a.admin.fullName);
  assert.notEqual(result.admin.id, a.admin.id);
  assert.ok(result.admin.personId);
  assert.equal((await findRecord<Staff>(db.sql, 'staff', a.admin.id))?.personId, result.admin.personId);
  assert.equal(await findStaffEmail(db.sql, result.facility.id, result.admin.id), await findStaffEmail(db.sql, a.facility.id, a.admin.id));
  assert.ok('identity' in await verifyCredential(db.sql, result.device.credential));
  const [separate] = await db.sql`SELECT (SELECT count(*) FROM patients WHERE facility_id=${input.code})::int AS patients,(SELECT count(*) FROM staff WHERE facility_id=${input.code})::int AS staff`;
  assert.deepEqual(separate, { patients: 0, staff: 1 });
  assert.equal((await findRecord<Staff>(db.sql, 'staff', nurse.id))?.facilityId, a.facility.id);
  const replay = await post('/organization/facilities', input);
  assert.equal(replay.statusCode, 201, replay.body);
  assert.deepEqual(replay.json(), result);
  const changed = await post('/organization/facilities', { ...input, name: 'Changed retry' });
  assert.equal(changed.statusCode, 409); assert.equal(changed.json().error, 'request_changed');
  const [counts] = await db.sql`SELECT (SELECT count(*) FROM organizations)::int AS organizations,(SELECT count(*) FROM organization_facility_creations)::int AS creations`;
  assert.deepEqual(counts, { organizations: 1, creations: 1 });
  const directory = (await post('/organization/facilities/list')).json();
  assert.equal(directory.organization.id, result.organization.id);
  assert.equal(directory.facilities.length, 2);
  assert.ok(directory.facilities.every((facility: { accessible: boolean }) => facility.accessible));
  assert.equal((await post('/organization/facilities/defaults', {}, nurse.id)).statusCode, 403);
  assert.equal((await post('/organization/facilities', input, nurse.id)).statusCode, 403);
  assert.equal((await post('/organization/facilities/list', {}, result.admin.id)).statusCode, 403);
  const nurseDirectory = (await post('/organization/facilities/list', {}, nurse.id)).json();
  assert.equal(nurseDirectory.canCreateFacility, false);
  assert.equal(nurseDirectory.facilities.find((facility: { id: string }) => facility.id === input.code).accessible, false);
  const opening = { facilityId: input.code, ...proof() };
  const opened = await post('/organization/facilities/open', opening);
  assert.equal(opened.statusCode, 200, opened.body);
  assert.equal(opened.json().staffId, result.admin.id);
  assert.equal(opened.json().personId, result.admin.personId);
  assert.ok('identity' in await verifyCredential(db.sql, opened.json().device.credential));
  const reopened = await post('/organization/facilities/open', opening);
  assert.equal(reopened.statusCode, 200, reopened.body);
  assert.deepEqual(reopened.json(), opened.json());
  assert.equal((await post('/organization/facilities/open', { facilityId: input.code, ...proof() }, nurse.id)).statusCode, 403);
  const unrelated = await registerScratchFacility(db.sql);
  assert.equal((await post('/organization/facilities/open', { facilityId: unrelated.facility.id, ...proof() })).statusCode, 403);

  // A receiving facility grants a separate, restricted membership to this nurse.
  const request = await post('/organization/staff-requests', { staffId: nurse.id, toFacilityId: input.code });
  assert.equal(request.statusCode, 201, request.body);
  const accepted = await app.inject({ method: 'POST', url: `/organization/staff-requests/${encodeURIComponent(request.json().id)}/accept`, headers: asDevice(result.device.credential), payload: { actorStaffId: result.admin.id, role: 'nurse', permission: 'read_only' } });
  assert.equal(accepted.statusCode, 201, accepted.body);
  const nurseNewDevice = { facilityId: input.code, ...proof() };
  const deniedEnrollment = await post('/organization/facilities/open', nurseNewDevice, nurse.id);
  assert.equal(deniedEnrollment.statusCode, 403); assert.equal(deniedEnrollment.json().error, 'device_approval_required');
  assert.equal((await db.sql`SELECT id FROM devices WHERE id=${nurseNewDevice.deviceId}`).length, 0);
  const nurseOnEnrolledDevice = await post('/organization/facilities/open', { facilityId: input.code, deviceId: result.device.deviceId }, nurse.id);
  assert.equal(nurseOnEnrolledDevice.statusCode, 200, nurseOnEnrolledDevice.body);
  assert.equal(nurseOnEnrolledDevice.json().staffId, accepted.json().staffId);
  assert.equal(nurseOnEnrolledDevice.json().device, undefined);
  await db.sql`UPDATE staff SET active=false WHERE facility_id=${input.code} AND id=${result.admin.id}`;
  const revoked = await post('/organization/facilities/open', opening);
  assert.equal(revoked.statusCode, 403); assert.equal(revoked.json().error, 'not_provisioned');
});

test('missing verified admin email refuses additional facility creation without creating an organization', async (t) => {
  const db = await scratchDatabase(); t.after(() => db.drop());
  const app = testApp(db.sql); t.after(() => app.close());
  const a = await registerScratchFacility(db.sql);
  await db.sql`DELETE FROM staff_contacts WHERE facility_id=${a.facility.id}`;
  const response = await app.inject({ method: 'POST', url: '/organization/facilities', headers: asDevice(a.device.credential), payload: { actorStaffId: a.admin.id, code: scratchFacilityCode(), name: 'Synthetic facility', state: 'Lagos', lga: 'Eti-Osa', level: 'phc', organizationName: 'Synthetic organization', requestId: randomUUID(), ...proof() } });
  assert.equal(response.statusCode, 403); assert.equal(response.json().error, 'verified_email_required');
  assert.equal((await db.sql`SELECT id FROM organizations`).length, 0);
  assert.equal((await db.sql`SELECT id FROM facilities`).length, 1);
});
